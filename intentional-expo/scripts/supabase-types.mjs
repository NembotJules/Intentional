/** Regenerate types/supabase.ts from the live schema (Management API). Run after every Supabase migration. */
import fs from 'fs';
import path from 'path';
import { loadAdminEnv } from './supabase-env.mjs';

const loaded = loadAdminEnv(['SUPABASE_PROJECT_REF', 'SUPABASE_ACCESS_TOKEN']);
if (loaded.missing) {
  console.error(`Missing ${loaded.missing.join(', ')}`);
  process.exit(1);
}
const { SUPABASE_PROJECT_REF: ref, SUPABASE_ACCESS_TOKEN: token } = loaded.env;
const r = await fetch(`https://api.supabase.com/v1/projects/${ref}/types/typescript?included_schemas=public`, { headers: { Authorization: `Bearer ${token}` } });
if (!r.ok) throw new Error(`types failed (${r.status}): ${(await r.text()).slice(0, 300)}`);
const { types } = await r.json();
const out = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'types', 'supabase.ts');
fs.writeFileSync(out, `// Generated by scripts/supabase-types.mjs from the live schema. Do not edit by hand.\n${types}`);
console.log(`wrote ${out}`);
